import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createApp } from './server.mjs'

async function withServer(python,run) {
    const server = createApp({ python })
    await new Promise(resolve => server.listen(0,'127.0.0.1',resolve))
    try { await run(`http://127.0.0.1:${server.address().port}`) }
    finally { await new Promise(resolve => server.close(resolve)) }
}
function post(url,body) {
    return fetch(url + '/api/compile',{ method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
}
test('HTTP compile runs Python with the selected in-memory entry and imports',async () => {
    await withServer(process.env.TIPY_PYTHON || 'python',async url => {
        const response = await post(url,{ files: { 'main.tip': 'not valid', 'other.tip': 'import utils\nint A=B+4', 'utils.tip': 'int B=3' }, entry: 'other.tip' })
        assert.equal(response.status,200)
        const result = await response.json()
        assert.equal(result.compiler,'python')
        assert.match(result.assembly,/Generated by TiPy/)
        assert.deepEqual(Object.keys(result.source_symbols),['B','A'])
        assert.deepEqual(Object.keys(result.symbols),[])
        assert.doesNotMatch(result.assembly,/__heap_start/)
        const reference = await (await post(url,{files:{'main.tip':'int x=7'},entry:'main.tip',optimization:'reference'})).json()
        assert.deepEqual(Object.keys(reference.symbols),['x'])
        assert.match(reference.assembly,/ld hl,7/)
        const stripes = await (await post(url,{files:{
            'main.tip':'from utils import get_evens\n#define HEIGHT 64\nint x=list(range(96))\nclear()\nfor col in range(0,96,2):\n    for pixel in range(HEIGHT):\n        pixel_on(col,pixel)\nrender()',
            'utils.tip':'def get_evens(int[] x) -> int[]:\n    return [n for n in x if n%2==0]'
        },entry:'main.tip'})).json()
        assert.equal(stripes.ok,true)
        assert.match(stripes.assembly,/ld \(hl\),170/)
        assert.doesNotMatch(stripes.assembly,/__heap_start|__fn_/)
    })
})
test('HTTP compile resolves callbacks throughout the complete feature demo',async()=>{
    const source=await readFile(new URL('../../examples/feature_test.tip',import.meta.url),'utf8')
    await withServer(process.env.TIPY_PYTHON || 'python',async url=>{
        for(const page of ['01','05','17','20']) {
            const response=await post(url,{files:{'main.tip':source.replace(/test_01\(\)\s*$/,`test_${page}()`)},entry:'main.tip'})
            const result=await response.json()
            assert.equal(response.status,200,JSON.stringify(result.error))
            assert.equal(result.ok,true)
        }
    })
})
