test('HTTP compile returns Python source locations and no assembly on failure',async () => {
    await withServer(process.env.TIPY_PYTHON || 'python',async url => {
        const response = await post(url,{ files: { 'main.tip': 'import utils\nint A=1', 'utils.tip': '# comment\nint B=missing' }, entry: 'main.tip' })
        assert.equal(response.status,422)
        const result = await response.json()
        assert.equal(result.error.filename,'utils.tip')
        assert.equal(result.error.line,2)
        assert.match(result.error.message,/not been declared/)
        assert.equal(result.assembly,undefined)
    })
})
test('Unavailable Python reports failure rather than falling back to JavaScript',async () => {
    await withServer('missing-tipy-python-executable',async url => {
        const response = await post(url,{ files: { 'main.tip': 'int A=1' }, entry: 'main.tip' })
        assert.equal(response.status,503)
        assert.match((await response.json()).error.message,/Python was not found/)
    })
    assert.doesNotMatch(await readFile(new URL('dist/app.js',import.meta.url),'utf8'),/function compilePyTie/)
})
test('Malformed requests are rejected',async () => {
    await withServer(process.env.TIPY_PYTHON || 'python',async url => {
        assert.equal((await fetch(url + '/api/compile')).status,405)
        assert.equal((await post(url,{ files: { '../secret.tip': 'int A=1' }, entry: '../secret.tip' })).status,422)
        assert.equal((await post(url,{ files: [], entry: 'main.tip' })).status,422)
    })
})
