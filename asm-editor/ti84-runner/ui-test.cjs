const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
    const browser = await chromium.launch({ headless: true, channel: 'msedge' })
    try {
        const page = await browser.newPage({ viewport: { width: 1400, height: 810 } })
        const errors = []
        page.on('pageerror',error => errors.push(error.message))
        await page.goto('http://127.0.0.1:8084')
        const source = page.locator('#source')
        const tab = name => page.locator('#tabs').getByRole('button',{ name, exact: true })
        assert.match(await source.inputValue(),/int x = 48/)
        assert.equal(await source.getAttribute('readonly'),null)
        assert.equal(await page.locator('#tabs .entry-badge').count(),1)
        const inactiveColor = await tab('utils.tip').evaluate(el => getComputedStyle(el).color)
        const activeColor = await tab('main.tip').evaluate(el => getComputedStyle(el).color)
        assert.notEqual(inactiveColor,activeColor,'Inactive tabs should be dimmed')
        const sourceCode = await source.inputValue()
        await page.screenshot({ path: 'simple-source-preview.png', fullPage: true })
        await page.locator('#run').click()
        await page.waitForFunction(() => document.querySelector('#source').readOnly)
        assert.match(await source.inputValue(),/org userMem/)
        assert.match(await source.inputValue(),/out \(1\),a/)
        assert.equal(await tab('Z80 assembly').count(),1)
        await page.waitForFunction(() => {
            const data = document.querySelector('canvas').getContext('2d').getImageData(0,0,96,64).data
            return data[(32 * 96 + 48) * 4] === 0
        })
        const pixel = () => page.evaluate(() => {
            const data = document.querySelector('canvas').getContext('2d').getImageData(0,0,96,64).data
            for (let i = 0; i < 6144; i++) if (data[i * 4] === 0) return i
            return -1
        })
        await page.locator('#calculator').focus()
        const before = await pixel()
        await page.keyboard.down('ArrowRight')
        await page.waitForTimeout(300)
        await page.keyboard.up('ArrowRight')
        const after = await pixel()
        assert.ok(after > before,`Expected keyboard movement: ${before} -> ${after}`)
        await page.waitForTimeout(150)
        assert.equal(await pixel(),after)
        const box = await page.locator('[data-code="2"]').boundingBox()
        await page.mouse.move(box.x + box.width / 2,box.y + box.height / 2)
        await page.mouse.down()
        await page.waitForTimeout(250)
        await page.mouse.move(20,20)
        await page.mouse.up()
        const pointerAfter = await pixel()
        assert.ok(pointerAfter < after)
        await page.waitForTimeout(150)
        assert.equal(await pixel(),pointerAfter,'Release outside must stop movement')
        await page.locator('#pause').click()
        await page.screenshot({ path: 'simple-assembly-preview.png', fullPage: true })
        await tab('main.tip').click()
        assert.equal(await source.inputValue(),sourceCode,'Source should survive showing assembly')
        await tab('utils.tip').click()
        await source.fill('int offset = 8\n')
        await tab('main.tip').click()
        await source.fill('import utils\npixel(offset, 3)\npresent()\nprint("HELLO")\n')
        await page.locator('#run').click()
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Finished')
        assert.ok(await pixel() >= 0)
        await tab('main.tip').click()
        await source.fill('u8 brightness = 300')
        await page.locator('#run').click()
        assert.match(await page.locator('#status').textContent(),/main.tip:1:.*outside u8/)
        assert.equal(await tab('Z80 assembly').count(),0)
        assert.equal(await page.locator('#pause').isHidden(),true)
        assert.equal(await pixel(),-1,'Error must clear stale display')
        await source.fill(sourceCode)
        await page.reload()
        assert.equal(await source.inputValue(),sourceCode,'Files should persist')
        await tab('utils.tip').click()
        await source.fill('pixel(12, 6)\npresent()\n')
        await page.getByRole('button',{ name: 'Set utils.tip as entry file', exact: true }).click()
        await tab('main.tip').click()
        await source.fill('bad syntax should not compile')
        await page.locator('#run').click()
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Finished')
        assert.match(await source.inputValue(),/utils.tip:1/,'Compile must use entry rather than active editor')
        assert.equal(await pixel(),6 * 96 + 12)
        await page.reload()
        assert.equal(await page.getByRole('button',{ name: 'Set utils.tip as entry file', exact: true }).getAttribute('aria-pressed'),'true')
        assert.match(await source.inputValue(),/pixel\(12, 6\)/)
        await page.screenshot({ path: 'entry-file-preview.png', fullPage: true })
        await page.setViewportSize({ width: 390, height: 844 })
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true)
        await page.screenshot({ path: 'simple-mobile-preview.png', fullPage: true })
        assert.deepEqual(errors,[])
        await page.evaluate(() => {
            localStorage.removeItem('tipy-project')
            localStorage.setItem('pytie-project',JSON.stringify({ 'main.pti': 'int legacy = 12', 'utils.pti': '# saved work' }))
        })
        await page.reload()
        assert.equal(await page.locator('#files').getByText('main.tip',{ exact: true }).count(),1)
        assert.equal(await source.inputValue(),'int legacy = 12')
        console.log('PASS: .tip sources/imports, dimmed tabs, selectable persistent entry, compile selection, legacy migration, LCD/input and mobile layout')
    } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
