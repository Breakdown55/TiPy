const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert=require('node:assert/strict')
const {resolve}=require('node:path')
const demo=process.env.TIPY_DEMO || 'ion_dash'
;(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'})
    try {
        const page=await browser.newPage({viewport:{width:1400,height:810}})
        const errors=[];page.on('pageerror',error=>errors.push(error.message))
        await page.goto('http://127.0.0.1:8084')
        await page.locator('#open').setInputFiles(resolve(`../../examples/${demo}.tip`))
        await page.waitForFunction(demo=>document.querySelector('#status').textContent===`Opened ${demo}.tip`,demo)
        await page.getByRole('button',{name:`Set ${demo}.tip as entry file`,exact:true}).click()
        await page.locator('#run').click()
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Compiled · '))
        console.log(await page.locator('#status').textContent())
        await page.locator('#execute').click()
        await page.waitForTimeout(300)
        const image=()=>page.locator('#lcd').evaluate(c=>c.toDataURL())
        await page.locator('#lcd').screenshot({path:`dist/${demo}-title.png`})
        const title=await image()
        const press=async key=>{await page.keyboard.down(key);await page.waitForTimeout(160);await page.keyboard.up(key);await page.waitForTimeout(160)}
        await press('Enter')
        assert.notEqual(await image(),title)
        await page.keyboard.down('ArrowRight');await press('Control');await page.keyboard.up('ArrowRight')
        await press('Enter')
        const paused=await image();await page.waitForTimeout(300);assert.equal(await image(),paused)
        await page.locator('#lcd').screenshot({path:`dist/${demo}-paused.png`})
        await press('Enter')
        await page.waitForFunction(previous=>document.querySelector('#lcd').toDataURL()!==previous,paused)
        await page.locator('#lcd').screenshot({path:`dist/${demo}-play.png`})
        await page.screenshot({path:`dist/${demo}-browser.png`,fullPage:true})
        await page.keyboard.down('Escape')
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Finished · '))
        await page.keyboard.up('Escape');assert.deepEqual(errors,[])
        console.log('PASS: ION DASH starts, handles arrows and dash, pauses/resumes, and exits')
    } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
