const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert=require('node:assert/strict')
const {resolve}=require('node:path')
;(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'})
    try {
        const page=await browser.newPage({viewport:{width:1400,height:810}})
        const errors=[];page.on('pageerror',error=>errors.push(error.message))
        await page.goto('http://127.0.0.1:8084')
        await page.locator('#open').setInputFiles(resolve('../../examples/mesh_lab.tip'))
        await page.waitForFunction(()=>document.querySelector('#status').textContent==='Opened mesh_lab.tip')
        await page.getByRole('button',{name:'Set mesh_lab.tip as entry file',exact:true}).click()
        await page.locator('#run').click()
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Compiled · '))
        console.log(await page.locator('#status').textContent())
        await page.locator('#execute').click();await page.waitForTimeout(350)
        const image=()=>page.locator('#lcd').evaluate(c=>c.toDataURL())
        const press=async key=>{await page.keyboard.down(key);await page.waitForTimeout(180);await page.keyboard.up(key);await page.waitForTimeout(200)}
        const initial=await image()
        await page.waitForFunction(previous=>document.querySelector('#lcd').toDataURL()!==previous,initial)
        await press('Enter')
        const paused=await image();await page.waitForTimeout(250);assert.equal(await image(),paused)
        await page.locator('#lcd').screenshot({path:'dist/mesh-cube.png'})
        await press('ArrowRight');assert.notEqual(await image(),paused)
        await press('Control');await page.locator('#lcd').screenshot({path:'dist/mesh-ship.png'})
        const ship=await image();await press('Control');assert.notEqual(await image(),ship)
        const crystal=await image();await press('+');assert.notEqual(await image(),crystal)
        await page.locator('#lcd').screenshot({path:'dist/mesh-crystal.png'})
        await page.screenshot({path:'dist/mesh-browser.png',fullPage:true})
        await press('Enter')
        const spinning=await image();await page.waitForFunction(previous=>document.querySelector('#lcd').toDataURL()!==previous,spinning)
        await page.keyboard.down('Escape')
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Finished · '))
        await page.keyboard.up('Escape');assert.deepEqual(errors,[])
        console.log('PASS: mesh rotation, model selection, scale, auto-spin and exit work in the browser')
    } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
