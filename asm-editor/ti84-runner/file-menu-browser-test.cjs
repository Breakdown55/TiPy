const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'})
    try {
        const page=await browser.newPage({viewport:{width:1400,height:810}})
        const errors=[]
        page.on('pageerror',error=>errors.push(error.message))
        await page.goto('http://127.0.0.1:8084')
        const source=page.locator('#source')
        const file=name=>page.locator('#files .file').filter({hasText:name})
        const tab=name=>page.locator('#tabs').getByRole('button',{name,exact:true})
        const menu=page.getByRole('menu')
        const setEntry=()=>menu.getByRole('menuitem',{name:'Set as entry',exact:true})
        const remove=()=>menu.getByRole('menuitem',{name:'Delete',exact:true})
        const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('tipy-project')))

        await file('utils.tip').click({button:'right'})
        assert.equal(await menu.isVisible(),true)
        assert.equal(await setEntry().isEnabled(),true)
        assert.equal(await source.getAttribute('aria-label'),'main.tip source code','Right click must not switch editors')
        await setEntry().click()
        assert.equal((await saved()).entry,'utils.tip')
        assert.equal(await menu.isVisible(),false)
        await page.reload()
        assert.equal(await page.getByRole('button',{name:'Set utils.tip as entry file',exact:true}).getAttribute('aria-pressed'),'true')

        await source.fill('clear()\npixel_on(2,3)\nrender()')
        await page.locator('#run').click()
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Compiled · '))
        assert.equal(await page.locator('#execute').isEnabled(),true)
        await tab('utils.tip').click({button:'right'})
        assert.equal(await setEntry().isDisabled(),true)
        await remove().click()
        assert.equal(await file('utils.tip').count(),0)
        assert.equal(await tab('utils.tip').count(),0)
        assert.equal(await tab('Z80 assembly').count(),0)
        assert.equal(await page.locator('#execute').isDisabled(),true)
        assert.equal((await saved()).entry,'main.tip')
        assert.equal(await page.locator('#undo-delete').isVisible(),true)
        await page.reload()
        assert.equal(await file('utils.tip').count(),0)
        await page.locator('#undo-delete').click()
        assert.equal((await saved()).entry,'utils.tip')
        assert.equal(await source.inputValue(),'clear()\npixel_on(2,3)\nrender()')

        await file('main.tip').focus()
        await page.keyboard.press('Shift+F10')
        assert.equal(await menu.isVisible(),true)
        await page.keyboard.press('ArrowDown')
        assert.equal(await remove().evaluate(element=>element===document.activeElement),true)
        await page.keyboard.press('Escape')
        assert.equal(await menu.isVisible(),false)
        assert.equal(await file('main.tip').evaluate(element=>element===document.activeElement),true)
        await file('main.tip').click({button:'right'})
        await source.click()
        assert.equal(await menu.isVisible(),false)

        await page.locator('#open').setInputFiles({name:'level.obj',mimeType:'text/plain',buffer:Buffer.from('o wall\nv 0 0 0')})
        await page.waitForFunction(()=>document.querySelector('#status').textContent==='Opened level.obj')
        await file('level.obj').click({button:'right'})
        assert.equal(await setEntry().isDisabled(),true)
        await page.screenshot({path:'dist/file-menu-preview.png',fullPage:true})
        await page.keyboard.press('Escape')
        for(const name of ['utils.tip','main.tip']){
            await file(name).click({button:'right'})
            await remove().click()
        }
        assert.equal((await saved()).entry,null)
        assert.equal(await page.locator('#run').isDisabled(),true)
        await page.reload()
        assert.equal(await file('main.tip').count(),0)
        assert.equal(await source.getAttribute('aria-label'),'level.obj source code')
        await file('level.obj').click({button:'right'})
        await remove().click()
        assert.equal(await page.locator('#files .file').count(),0)
        assert.equal(await source.inputValue(),'')
        assert.equal(await source.getAttribute('placeholder'),'Open or create a file')
        await page.reload()
        assert.equal(await page.locator('#files .file').count(),0)
        await page.locator('#undo-delete').click()
        assert.equal(await source.inputValue(),'o wall\nv 0 0 0')
        assert.equal(await page.locator('#run').isDisabled(),true)

        page.once('dialog',dialog=>dialog.accept('fresh.tip'))
        await page.locator('#new-file').click()
        assert.equal((await saved()).entry,'fresh.tip')
        assert.equal(await page.locator('#run').isEnabled(),true)
        await page.setViewportSize({width:390,height:844})
        await file('fresh.tip').evaluate(element=>element.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:389,clientY:843})))
        const bounds=await menu.boundingBox()
        assert.ok(bounds&&bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=390&&bounds.y+bounds.height<=844,JSON.stringify({bounds,viewport:await page.evaluate(()=>({width:innerWidth,height:innerHeight,scroll:scrollY,menu:document.querySelector("#file-menu").outerHTML,position:getComputedStyle(document.querySelector("#file-menu")).position}))}))
        await page.keyboard.press('Escape')
        assert.deepEqual(errors,[])
        console.log('PASS: right-click entry/delete, tabs, compile invalidation, persisted undo, keyboard, assets, empty projects and viewport bounds')
    } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
