const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const {resolve}=require('node:path')
const assert=require('node:assert/strict')
;(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'})
    try {
        const page=await browser.newPage({viewport:{width:1400,height:810}})
        const errors=[];page.on('pageerror',error=>errors.push(error.message))
        await page.goto('http://127.0.0.1:8084')
        await page.locator('#open').setInputFiles([resolve('../../examples/lumen_gallery.tip'),resolve('../../examples/lumen_gallery.obj')])
        await page.waitForFunction(()=>document.querySelector('#status').textContent==='Opened 2 files')
        assert.equal(await page.getByRole('button',{name:'Set lumen_gallery.tip as entry file',exact:true}).getAttribute('aria-pressed'),'true')
        await page.locator('#run').click()
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Compiled · '))
        console.log(await page.locator('#status').textContent())
        await page.locator('#execute').click()
        await page.waitForFunction(()=>Array.from(document.querySelector('#lcd').getContext('2d').getImageData(0,0,96,64).data).some((v,i)=>i%4!==3&&v===0))
        await page.locator('#lcd').click()
        await page.locator('#lcd').screenshot({path:'dist/gallery-browser-start.png'})
        for(const key of ['ArrowUp','ArrowRight']) {
            const image=await page.locator('#lcd').evaluate(canvas=>canvas.toDataURL())
            await page.keyboard.down(key)
            await page.waitForFunction(previous=>document.querySelector('#lcd').toDataURL()!==previous,image)
            await page.keyboard.up(key)
        }
        await page.keyboard.down('Control');await page.keyboard.down('ArrowLeft')
        await page.waitForTimeout(400)
        await page.keyboard.up('ArrowLeft');await page.keyboard.up('Control')
        await page.screenshot({path:'dist/gallery-browser.png',fullPage:true})
        await page.keyboard.down('Escape')
        await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Finished · '))
        await page.keyboard.up('Escape')
        assert.deepEqual(errors,[])
        console.log('PASS: multi-file open, automatic entry, OBJ scene, held movement/turning/strafe, exit')
    } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
