const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const { createServer } = require('node:http')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const { emulatorHtml } = require('../src/webview.cjs')
const { runPython } = require('../src/project.cjs')
const root = path.resolve(__dirname, '..')
const compiler = path.join(root, 'dist/compiler')
const compile = async source => {
    const result = await runPython(process.env.TIPY_PYTHON || 'python', ['-I', path.join(compiler, 'bridge.py')], { files: { 'main.tip': source }, entry: 'main.tip' }, { cwd: compiler })
    assert(result.ok, JSON.stringify(result.error)); return result.assembly
}
;(async () => {
    const server = createServer(async (request, response) => {
        const target = { '/emulator.js': 'dist/emulator.js', '/emulator.css': 'media/emulator.css' }[request.url]
        if (target) {
            response.setHeader('Content-Type', target.endsWith('.js') ? 'text/javascript' : 'text/css')
            response.end(await fs.readFile(path.join(root, target)))
        } else {
            response.setHeader('Content-Type', 'text/html')
            response.end(emulatorHtml({ cspSource: "'self'", script: '/emulator.js', style: '/emulator.css', nonce: 'test-nonce' }))
        }
    })
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
    let browser
    try {
        browser = await chromium.launch({ headless: true, channel: 'msedge' })
        const page = await browser.newPage({ viewport: { width: 760, height: 900 } })
        const errors = []
        page.on('pageerror', error => errors.push(error.message))
        await page.addInitScript(() => { window.messages = []; window.acquireVsCodeApi = () => ({ postMessage: message => window.messages.push(message) }) })
        await page.goto(`http://127.0.0.1:${server.address().port}`)
        await page.waitForFunction(() => window.messages.some(message => message.type === 'ready'))
        const send = async assembly => page.evaluate(assembly => window.postMessage({ type: 'run', assembly, filename: 'main.tip' }, '*'), assembly)
        const pixel = async (x, y) => page.locator('canvas').evaluate((canvas, [x, y]) => canvas.getContext('2d').getImageData(x, y, 1, 1).data[0], [x, y])
        await send(await compile('clear()\npixel_on(7,4)\nrender()\n'))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Finished')
        assert.equal(await pixel(7, 4), 0)
        assert.equal(await pixel(6, 4), 255)
        await send(await compile(await fs.readFile(path.resolve(root, '../examples/gx_primitives.tip'), 'utf8')))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Finished')
        const black = await page.locator('canvas').evaluate(canvas => Array.from(canvas.getContext('2d').getImageData(0,0,96,64).data).filter((value,index) => index % 4 === 0 && value === 0).length)
        assert(black > 700, 'native XY/XYZ primitives and EGX text share one visible frame')
        await page.screenshot({ path: path.join(root, 'dist/gx-primitives-test.png'), fullPage: true })
        await send(await compile('clear()\nwhile not key_down("clear"):\n    if key_down("right"):\n        pixel_on(20,20)\n    else:\n        pixel_off(20,20)\n    render()\n'))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Running')
        await page.keyboard.down('ArrowRight')
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 0)
        await page.keyboard.up('ArrowRight')
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 255)
        await page.locator('#pause').click()
        assert.equal(await page.locator('#status').textContent(), 'Paused')
        await page.evaluate(() => {
            window.dispatchEvent(new Event('blur'))
            window.dispatchEvent(new Event('focus'))
            window.postMessage({ type: 'viewState', active: false }, '*')
            window.postMessage({ type: 'viewState', active: true }, '*')
        })
        await page.waitForTimeout(100)
        assert.equal(await page.locator('#status').textContent(), 'Paused', 'returning must not undo a manual pause')
        await page.locator('#pause').click()
        assert(await page.locator('canvas').evaluate(canvas => document.activeElement === canvas))
        await page.keyboard.down('ArrowRight')
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 0)
        await page.evaluate(() => window.dispatchEvent(new Event('blur')))
        assert.match(await page.locator('#status').textContent(), /^Paused/)
        await page.keyboard.up('ArrowRight')
        await page.evaluate(() => window.dispatchEvent(new Event('focus')))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Running')
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 255)
        await page.evaluate(() => window.postMessage({ type: 'viewState', active: false }, '*'))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Paused')
        await page.evaluate(() => window.dispatchEvent(new Event('focus')))
        assert.equal(await page.locator('#status').textContent(), 'Paused', 'inactive emulator must wait for its tab to be selected')
        await page.evaluate(() => window.postMessage({ type: 'viewState', active: true }, '*'))
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Running')
        assert(await page.locator('canvas').evaluate(canvas => document.activeElement === canvas))
        assert(await page.locator('details').evaluate(details => details.open))
        const arrow = await page.getByRole('button', { name: '→', exact: true }).boundingBox()
        await page.mouse.move(arrow.x + arrow.width / 2, arrow.y + arrow.height / 2)
        await page.mouse.down()
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 0)
        await page.mouse.up()
        await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(20,20,1,1).data[0] === 255)
        await page.locator('canvas').focus()
        await page.keyboard.down('Escape')
        await page.waitForFunction(() => document.querySelector('#status').textContent === 'Finished')
        await page.keyboard.up('Escape')
        await page.evaluate(() => window.postMessage({ type: 'viewState', active: true }, '*'))
        await page.waitForTimeout(100)
        assert.equal(await page.locator('#status').textContent(), 'Finished', 'returning cannot restart a finished program')
        assert.deepEqual(errors, [])
        for (const viewport of [{width:760,height:900}, {width:600,height:600}, {width:320,height:480}]) {
            await page.setViewportSize(viewport)
            const layout = await page.evaluate(() => {
                const screen = document.querySelector('canvas').getBoundingClientRect()
                const keypad = document.querySelector('#keys').getBoundingClientRect()
                return { screen: { width: screen.width, height: screen.height }, bottom: keypad.bottom,
                    right: keypad.right, top: screen.top,
                    metadataBottom: document.querySelector('#metadata').getBoundingClientRect().bottom,
                    scrollHeight: document.documentElement.scrollHeight }
            })
            assert(layout.bottom <= viewport.height + 1, `keypad fits ${JSON.stringify(viewport)}: ${JSON.stringify(layout)}`)
            assert(layout.right <= viewport.width + 1)
            assert(layout.scrollHeight <= viewport.height + 1)
            assert(layout.metadataBottom <= layout.top)
            assert(Math.abs(layout.screen.width / layout.screen.height - 1.5) < .02)
            assert(!(await page.locator('body').innerText()).includes('Click the screen for keyboard input.'))
        }
        await page.setViewportSize({width:600,height:600})
        await page.screenshot({ path: path.join(root, 'dist/emulator-test.png'), fullPage: true })
        console.log('PASS: real Z80 output, automatic blur/tab resume, manual pause preservation, held-key release, keypad, and Clear exit')
    } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)) }
})().catch(error => { console.error(error); process.exitCode = 1 })
