const { test, after } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { collectProject, runPython } = require('../src/project.cjs')
const { measureAssembly } = require('../dist/assembler.cjs')
const compiler = path.resolve(__dirname, '../dist/compiler')
const work = path.resolve(__dirname, '../dist/test-project')
const python = process.env.TIPY_PYTHON || 'python'
const invoke = request => runPython(python, ['-I', path.join(compiler, 'bridge.py')], request, { cwd: compiler })
test('compile dirty imported source, assemble it, and attribute import diagnostics', async () => {
    await fs.mkdir(work, { recursive: true })
    await fs.writeFile(path.join(work, 'main.tip'), 'import utils\nclear()\npixel_on(utils.value(), 3)\nrender()\n')
    await fs.writeFile(path.join(work, 'utils.tip'), 'def value() -> int:\n    return 1\n')
    const project = await collectProject(path.join(work, 'main.tip'), [{ uri: { scheme: 'file', fsPath: path.join(work, 'utils.tip') }, getText: () => 'def value() -> int:\n    return 7\n' }])
    assert(project.files['utils.tip'].includes('return 7'))
    const result = await invoke(project)
    assert.equal(result.ok, true, JSON.stringify(result.error))
    assert(result.assembly.includes('Generated by TiPy'))
    assert(measureAssembly(result.assembly).machineBytes > 0)
    project.files['utils.tip'] = 'def value() -> int:\n    return missing\n'
    const invalid = await invoke({ ...project, mode: 'check' })
    assert.equal(invalid.ok, false)
    assert.equal(invalid.error.filename, 'utils.tip')
    assert.equal(invalid.error.line, 2)
})
test('bundled helper modules and the shared GX/EGX transform pipeline compile', async () => {
    const source = 'import egx\nfrom timing import Clock\negx.init()\nclock = Clock()\negx.clear()\negx.push_matrix()\negx.translate(20, 10)\negx.draw_rect(0, 0, 8, 8)\negx.pop_matrix()\negx.render()\negx.quit()\n'
    const result = await invoke({ files: { 'main.tip': source }, entry: 'main.tip' })
    assert.equal(result.ok, true, JSON.stringify(result.error))
    const sizes = measureAssembly(result.assembly)
    assert(sizes.machineBytes < 24170)
    assert.equal(sizes.codeDataBytes + sizes.heapBytes, sizes.machineBytes)
})
test('compiler bridge rejects paths and invalid profiles', async () => {
    const bad = await invoke({ files: { '../main.tip': 'pass\n' }, entry: '../main.tip' })
    assert.equal(bad.ok, false)
    const invalid = await invoke({ files: { 'main.tip': 'pass\n' }, entry: 'main.tip', optimization: 'unknown' })
    assert.equal(invalid.ok, false)
})
test('timeouts and cancellation terminate compiler subprocesses', async () => {
    await assert.rejects(runPython(python, ['-c', 'import time; time.sleep(30)'], {}, { timeout: 100 }), /timed out/)
    const controller = new AbortController()
    const pending = runPython(python, ['-c', 'import time; time.sleep(30)'], {}, { signal: controller.signal })
    controller.abort()
    await assert.rejects(pending, /cancelled/)
})
after(async () => { await fs.rm(work, { recursive: true, force: true }) })
