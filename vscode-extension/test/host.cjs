const vscode = require('vscode')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
async function replace(document, text) {
    const edit = new vscode.WorkspaceEdit()
    edit.replace(document.uri, new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length)), text)
    assert(await vscode.workspace.applyEdit(edit))
}
async function run() {
    const folder = vscode.workspace.workspaceFolders[0].uri.fsPath
    const main = vscode.Uri.file(path.join(folder, 'main.tip'))
    const doc = await vscode.workspace.openTextDocument(main)
    await vscode.window.showTextDocument(doc)
    const extension = vscode.extensions.getExtension('Breakdown55.tipy')
    assert(extension, 'Packaged extension must be discoverable')
    const api = await extension.activate()
    await vscode.workspace.getConfiguration('tipy').update('liveDiagnostics', false, vscode.ConfigurationTarget.Workspace)
    const original = doc.getText()
    for (const text of ['import ', 'from ']) {
        await replace(doc, text)
        const result = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', main, new vscode.Position(0, text.length), ' ')
        for (const name of ['gx', 'egx', 'time', 'random', 'math', 'timing', 'utils']) assert(result.items.some(item => item.label === name), `${text} suggests ${name}`)
    }
    await replace(doc, 'from egx import clear, ')
    const selectedImports = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', main, new vscode.Position(0, doc.getText().length), ' ')
    assert(selectedImports.items.some(item => item.label === 'draw_rect' && !(item.insertText?.value || '').includes('(')), 'from-import offers bare exported names')
    assert(!selectedImports.items.some(item => item.label === 'clear'), 'already imported member is omitted')
    await replace(doc, '')
    const activeEditor = await vscode.window.showTextDocument(doc)
    activeEditor.selection = new vscode.Selection(0, 0, 0, 0)
    await vscode.commands.executeCommand('workbench.action.focusActiveEditorGroup')
    await vscode.commands.executeCommand('default:type', { text: 'import ' })
    await wait(700)
    await vscode.commands.executeCommand('acceptSelectedSuggestion')
    assert(/^import [A-Za-z_]\w*$/.test(doc.getText()), `typing import-space opens a usable suggestion list: ${JSON.stringify(doc.getText())}`)
    await vscode.commands.executeCommand('hideSuggestWidget')
    await replace(doc, 'import egx as e\ne.\n')
    const completions = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', main, new vscode.Position(1, 2), '.')
    assert(completions.items.some(item => item.label === 'draw_rect'), 'EGX completion')
    assert.match(String(completions.items.find(item => item.label === 'draw_rect').documentation.value || completions.items.find(item => item.label === 'draw_rect').documentation), /top-left/, 'completion describes the operation')
    assert(completions.items.some(item => item.label === 'push_matrix'), 'shared matrix completion')
    await replace(doc, 'import gx\ngx.\n')
    const gxCompletions = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', main, new vscode.Position(1, 3), '.')
    assert(gxCompletions.items.some(item => item.label === 'begin'), 'low-level submission completion')
    assert(gxCompletions.items.some(item => item.label === 'TRIANGLES' && item.kind === vscode.CompletionItemKind.Constant), 'primitive enum completion')
    assert(!gxCompletions.items.some(item => item.label === 'draw_rect'), 'convenience helpers are not GX members')
    await replace(doc, 'import gx\ngx.clear()\ngx.draw(gx.TRIANGLES,[(10,10),(40,10),(20,30)])\ngx.render()\n')
    assert((await vscode.commands.executeCommand('tipy.compile', main))?.ok, 'GX primitives compile through packaged extension')
    await replace(doc, 'pixel_on(3, 4)\n')
    const hover = await vscode.commands.executeCommand('vscode.executeHoverProvider', main, new vscode.Position(0, 3))
    assert(hover.length && hover.some(item => item.contents.some(content => String(content.value || content).includes('int x'))), 'hover signature')
    assert(hover.some(item => item.contents.some(content => String(content.value || content).includes('Sets the pixel'))), 'hover describes the function')
    const hint = await vscode.commands.executeCommand('vscode.executeSignatureHelpProvider', main, new vscode.Position(0, 12), ',')
    assert(hint.signatures[0].label.includes('pixel_on'), 'parameter hints')
    assert.match(String(hint.signatures[0].documentation.value || hint.signatures[0].documentation), /drawing buffer/, 'parameter hints include behavior documentation')
    await replace(doc, original)
    const helper = await vscode.workspace.openTextDocument(vscode.Uri.file(path.join(folder, 'utils.tip')))
    await replace(helper, 'def value() -> int:\n    return 7\n')
    const result = await vscode.commands.executeCommand('tipy.compile', main)
    assert(result?.ok, 'native compile command')
    assert(result.machineBytes > 0, 'real assembler byte count')
    assert.equal(vscode.window.activeTextEditor.document.uri.toString(), main.toString(), 'compile preserves source tab')
    await vscode.commands.executeCommand('tipy.showAssembly')
    assert(vscode.window.activeTextEditor.document.getText().includes('Generated by TiPy'), 'assembly viewer')
    const started = new Promise((resolve, reject) => {
        const timeout = setTimeout(() => { listener.dispose(); reject(new Error('Webview emulator did not report execution')) }, 15000)
        const listener = api.onDidChangeEmulatorState(message => {
            if (message.type === 'started') { clearTimeout(timeout); listener.dispose(); resolve(message) }
            if (message.type === 'error') { clearTimeout(timeout); listener.dispose(); reject(new Error(message.message)) }
        })
    })
    assert((await vscode.commands.executeCommand('tipy.run', main))?.ok, 'Run compiles and opens emulator')
    assert((await started).bytes > 0)
    await vscode.commands.executeCommand('tipy.stop')
    await vscode.commands.executeCommand('tipy.setEntry', main)
    assert.equal(vscode.workspace.getConfiguration('tipy', main).get('entryFile'), 'main.tip')
    await vscode.workspace.getConfiguration('tipy').update('liveDiagnostics', true, vscode.ConfigurationTarget.Workspace)
    await replace(helper, 'def value() -> int:\n    return missing\n')
    await vscode.window.showTextDocument(doc)
    let errors = []
    for (let i = 0; i < 60; i++) {
        errors = vscode.languages.getDiagnostics(helper.uri).filter(item => item.source === 'TiPy')
        if (errors.length) break
        await wait(100)
    }
    assert(errors.some(item => item.message.includes('missing') && item.range.start.line === 1), 'live unsaved import diagnostic')
    await replace(helper, 'def value() -> int:\n    return 7\n')
    for (let i = 0; i < 60 && vscode.languages.getDiagnostics(helper.uri).length; i++) await wait(100)
    assert.equal(vscode.languages.getDiagnostics(helper.uri).length, 0, 'diagnostics clear after fix')
    await fs.writeFile(path.join(folder, 'host-result.json'), JSON.stringify({ ok: true, machineBytes: result.machineBytes, checks: ['completion', 'hover', 'signature', 'dirty compilation', 'assembly viewer', 'webview execution', 'entry file', 'live import diagnostics'] }, null, 2))
    console.log('TiPy extension host integration passed')
}
module.exports = { run }
