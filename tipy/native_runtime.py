"""Demand-linked native standard library. Numeric ABI: HL result, IX preserved.

Fixed-point values are signed Q8.8. Trig tables are generated by the compiler;
the calculator only indexes tables and executes Z80 integer instructions.
"""

import math


def assembly(used):
    code = []
    if used & {'time.frame_ticks','time.stop_frame_timer'}:
        code.append('''__native_frame_timer_ready: db 0
__native_frame_ticks:
        ld a,(__native_frame_timer_ready)
        or a
        jr nz,__native_frame_read
        ld a,0x46
        out (0x30),a
        xor a
        out (0x31),a
        out (0x32),a
        inc a
        ld (__native_frame_timer_ready),a
__native_frame_read:
        in a,(0x32)
        neg
        ld l,a
        ld h,0
        ret
__native_stop_frame_timer:
        xor a
        out (0x30),a
        out (0x31),a
        ld (__native_frame_timer_ready),a
        ret''')
    if "sleep_integer" in used:
        code.append("""__native_sleep_integer:
        bit 7,h
        jp nz,__native_sleep_error
        ld a,h
        or a
        jp nz,__native_sleep_error
        ld a,l
        cp 33
        jp nc,__native_sleep_error
        ld de,1000
        jp __math_mul""")
    if "sleep_fixed" in used:
        code.append("""__native_sleep_fixed:
        push hl
        ld de,8389
        or a
        sbc hl,de
        pop hl
        jp nc,__native_sleep_error
        ld a,l
        and 31
        push af
        ld b,5
__native_sleep_shift:
        srl h
        rr l
        djnz __native_sleep_shift
        ld de,125
        call __math_mul
        ex (sp),hl
        ld l,h
        ld h,0
        ld de,125
        call __math_mul
        ld b,5
__native_sleep_remainder:
        srl h
        rr l
        djnz __native_sleep_remainder
        pop de
        add hl,de
        ret""")
    if "random.seed" in used:
        code.append("""__native_seed:
        ld (__native_rng_state),hl
        ret""")
    if "random.randint" in used:
        code.append("""__native_random:
        ld hl,(__native_rng_state)
        ld de,25173
        call __math_mul
        ld de,13849
        add hl,de
        ld (__native_rng_state),hl
        ld a,l
        xor h
        ld l,a
        ret
__native_randint:
        push ix
        ld ix,0
        add ix,sp
        ld l,(ix+6)
        ld h,(ix+7)
        ld e,(ix+4)
        ld d,(ix+5)
        push hl
        push de
        ld a,h
        xor 128
        ld h,a
        ld a,d
        xor 128
        ld d,a
        or a
        sbc hl,de
        pop hl
        pop de
        jp c,__native_randint_valid
        jp z,__native_randint_valid
        ld hl,9
        jp __native_fail
__native_randint_valid:
        or a
        sbc hl,de
        inc hl
        push hl
        ld a,h
        or l
        jp z,__native_randint_full
        dec hl
        ld d,h
        ld e,l
        ld b,16
__native_mask:
        srl d
        rr e
        ld a,h
        or d
        ld h,a
        ld a,l
        or e
        ld l,a
        djnz __native_mask
        push hl
__native_randint_retry:
        call __native_random
        ld a,l
        and (ix-4)
        ld l,a
        ld a,h
        and (ix-3)
        ld h,a
        push hl
        ld e,(ix-2)
        ld d,(ix-1)
        or a
        sbc hl,de
        pop hl
        jp nc,__native_randint_retry
        jp __native_randint_result
__native_randint_full:
        call __native_random
__native_randint_result:
        ld e,(ix+6)
        ld d,(ix+7)
        add hl,de
        ld sp,ix
        pop ix
        ret""")
    if used & {"random.seed", "random.randint"}:
        code.append("__native_rng_state: dw 44257")
    if "time.sleep" in used:
        code.append("""__native_sleep:
        bit 7,h
        jp nz,__native_sleep_error
        ld a,h
        or l
        ret z
__native_sleep_ms:
        in a,(32)
        and 1
        ld bc,228
        jp z,__native_sleep_tick
        ld bc,574
__native_sleep_tick:
        dec bc
        ld a,b
        or c
        jr nz,__native_sleep_tick
        dec hl
        ld a,h
        or l
        jp nz,__native_sleep_ms
        ret
__native_sleep_error:
        ld hl,10
        jp __native_fail""")
    if used & {"random.randint", "time.sleep"}:
        code.append("""__native_fail:
        ld (__list_error),hl
        ld sp,(__list_main_sp)
        ld ix,(__list_main_ix)
        ret""")
    if "math.radians" in used:
        code.append("""__native_radians:
        push hl
        ld de,360
        call __math_div
        ld de,1608
        call __math_mul
        ex (sp),hl
        ld de,360
        call __math_mod
        add hl,hl
        ld de,__native_radians_table
        add hl,de
        ld e,(hl)
        inc hl
        ld d,(hl)
        pop hl
        add hl,de
        ret
__native_radians_table:""")
        code.extend(words(round(math.radians(i) * 256) for i in range(360)))
    if used & {"math.sin", "math.cos"}:
        if "math.cos" in used:
            code.append("""__native_cos:
        ld de,1608
        call __math_mod
        ld de,402
        add hl,de
        jp __native_sin""")
        code.append("""__native_sin:
        ld de,1608
        call __math_mod
        add hl,hl
        ld de,__native_sin_table
        add hl,de
        ld e,(hl)
        inc hl
        ld d,(hl)
        ex de,hl
        ret
__native_sin_table:""")
        code.extend(words(round(math.sin(i * 2 * math.pi / 1608) * 256) for i in range(1608)))
    return "\n".join(code)


def words(values):
    values = list(values)
    return ["        dw " + ",".join(str(n & 65535) for n in values[i:i+16])
            for i in range(0, len(values), 16)]
