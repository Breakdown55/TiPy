"""Checked dictionaries -> assembly. Every expression leaves its result in HL."""

from .list_runtime import runtime_assembly, HEAP_BYTES, RUNTIME_TARGET
from .optimizer import optimize


def generate(tree, symbols, *, optimize_graphics=True):
    if "static_frames" in tree:
        from .framebuffer_backend import generate_frames
        return generate_frames(tree["static_frames"])
    def called_labels(item):
        if isinstance(item, dict):
            if item.get("unreachable"):
                return set()
            found = {item["symbol"]} if item.get("kind") == "call" and "symbol" in item else set()
            return found | set().union(*(called_labels(value) for value in item.values()))
        if isinstance(item, list):
            return set().union(*(called_labels(value) for value in item))
        return set()

    functions = {item["label"]: item for item in tree["body"] if item["kind"] == "function"}
    live = called_labels([item for item in tree["body"] if item["kind"] != "function"])
    pending = list(live)
    while pending:
        name = pending.pop()
        if name in functions:
            dependencies = called_labels(functions[name]["body"]) - live
            live.update(dependencies); pending.extend(dependencies)
    tree = {**tree, "body": [item for item in tree["body"] if item["kind"] != "function" or item["label"] in live]}
    from .drawing_optimizer import optimize_drawing
    if optimize_graphics:
        tree = optimize_drawing(tree)
    code = ["; Generated by TiPy", "        org 0x9D95"]
    serial = 0
    loops = []  # Innermost (condition label, exit label) is at the top.
    return_label = None

    def has_arrays(item):
        if isinstance(item, dict):
            if item.get("unreachable"):
                return False
            if item.get("iteration_kind") == "range":
                return has_arrays(item["body"]) or has_arrays(item["iterable"]["arguments"])
            return str(item.get("type", "")).endswith("[]") or item.get("kind") in {"list", "index", "method", "length"} or any(has_arrays(v) for v in item.values())
        if isinstance(item, list):
            return any(has_arrays(v) for v in item)
        return False

    lists_used = has_arrays(tree)
    modulo_used = False
    math_used = set()
    pixels_used = set()
    constant_data = {}
    from .optimization_pipeline import walk
    native_used = {item["name"] for item in walk(tree["body"]) if item.get("kind") == "stdlib"}
    if native_used & {"math.sin", "math.cos", "math.radians"}:
        modulo_used = True
    if native_used & {"math.radians", "random.randint"}:
        math_used.add("mul")
    if "math.radians" in native_used:
        math_used.add("div")

    def has_modulo(item):
        if isinstance(item, dict):
            if item.get("unreachable"):
                return False
            return item.get("iteration_kind") == "range" and "fast_range" not in item or item.get("kind") in {"modulo", "floor_divide"} or item.get("operator") in {"//=", "%="} or any(has_modulo(value) for value in item.values())
        return isinstance(item, list) and any(has_modulo(value) for value in item)

    errors_used = lists_used or has_modulo(tree) or bool(native_used)

    def label():
        nonlocal serial
        serial += 1
        return f"__L{serial}"

    def mark(name):
        code.append(name + ":")

    def emit(*instructions):
        code.extend("        " + instruction for instruction in instructions)

    def frame_address(offset):
        return f"(ix{offset:+d})"

    def buffer_address(slot):
        if slot.get("storage") == "frame":
            emit("push ix", "pop hl", f"ld de,{slot['offset'] & 65535}", "add hl,de")
        else:
            emit(f"ld hl,{slot['label']}")

    def load(item):
        byte = item["type"] in {"u8", "bool"}
        if item.get("storage") == "frame":
            emit(f"ld l,{frame_address(item['offset'])}")
            emit("ld h,0" if byte else f"ld h,{frame_address(item['offset'] + 1)}")
        elif byte:
            emit(f"ld a,({item['symbol']})", "ld l,a", "ld h,0")
        else:
            emit(f"ld hl,({item['symbol']})")

    def store(item):
        byte = item["type"] in {"u8", "bool"}
        if item.get("storage") == "frame":
            emit(f"ld {frame_address(item['offset'])},l")
            if not byte:
                emit(f"ld {frame_address(item['offset'] + 1)},h")
        elif byte:
            emit("ld a,l", f"ld ({item['symbol']}),a")
        else:
            emit(f"ld ({item['symbol']}),hl")

    def runtime(name, arguments):
        for argument in arguments:
            if isinstance(argument, int):
                emit(f"ld hl,{argument & 65535}")
            else:
                expression(argument)
            emit("push hl")
        emit(f"call __arr_{name}")
        for argument in reversed(arguments):
            emit("pop de")
            if isinstance(argument, dict) and argument.get("owned"):
                emit("push hl", "push de", "call __arr_release", "pop de", "pop hl")

    def read_length():
        # HL points to the stable descriptor. Length is a word at offset two.
        emit("inc hl", "inc hl", "ld e,(hl)", "inc hl", "ld d,(hl)", "ex de,hl")

    def expression(item):
        nonlocal modulo_used
        kind = item["kind"]
        if kind == "void_constant":
            return
        elif kind in {"number", "boolean"}:
            emit(f"ld hl,{int(item['value']) & 0xFFFF}")
        elif kind == "decimal":
            emit(f"ld hl,{item['raw'] & 65535}")
        elif kind == "to_fixed":
            expression(item["value"])
            emit("ld h,l", "ld l,0")
        elif kind == "cast_int":
            argument = item["arguments"][0]
            expression(argument)
            if argument["type"] == "fixed":
                positive = label()
                emit("bit 7,h", f"jp z,{positive}", "ld de,255", "add hl,de")
                mark(positive)
                emit("ld l,h", "ld h,0", "bit 7,l")
                end = label()
                emit(f"jp z,{end}", "dec h")
                mark(end)
        elif kind == "stdlib":
            name, args = item["name"], item["arguments"]
            if name == "random.randint":
                for arg in args:
                    expression(arg); emit("push hl")
                emit("call __native_randint", "pop de", "pop de")
            elif name == "time.sleep":
                if "milliseconds" in item:
                    emit(f"ld hl,{item['milliseconds']}")
                else:
                    expression(args[0])
                    conversion = "sleep_fixed" if args[0]["type"] == "fixed" else "sleep_integer"
                    native_used.add(conversion)
                    math_used.add("mul")
                    emit(f"call __native_{conversion}")
                emit("call __native_sleep")
            else:
                expression(args[0])
                if name in {"math.sin", "math.cos"} and args[0]["type"] != "fixed":
                    emit("ld h,l", "ld l,0")
                emit(f"call __native_{name.split('.')[-1]}")
        elif kind == "address":
            emit(f"ld hl,{item['label']}")
        elif kind == "constant_list":
            width = 2 if item["type"] == "i16[]" else 1
            if not item["values"]:
                runtime("new", [width])
            else:
                values = []
                for value in item["values"]:
                    values.append(int(value) & 255)
                    if width == 2: values.append((int(value) >> 8) & 255)
                key = tuple(values)
                if key not in constant_data:
                    constant_data[key] = f"__constant_data_{len(constant_data)}"
                runtime("from_data", [width, len(item["values"]), {"kind": "address", "label": constant_data[key]}])
        elif kind == "name":
            load(item)
        elif kind == "list":
            width = 2 if item["type"] == "i16[]" else 1
            runtime("new", [width])
            emit("push hl")
            for value in item["values"]:
                emit("pop hl", "push hl", "push hl")
                expression(value)
                emit("push hl", "call __arr_append", "pop de", "pop de")
            emit("pop hl")
        elif kind == "comprehension":
            runtime("new", [2 if item["type"] == "i16[]" else 1])
            emit("push hl")
            statements([item["loop"]])
            emit("pop hl")
        elif kind == "length":
            argument = item["arguments"][0]
            expression(argument)
            if argument.get("owned"):
                emit("push hl")
            read_length()
            if argument.get("owned"):
                emit("pop de", "push hl", "push de", "call __arr_release", "pop de", "pop hl")
        elif kind == "builtin":
            name, arguments = item["name"], item["arguments"]
            if name == "range":
                values = [0, arguments[0], 1] if len(arguments) == 1 else [*arguments, 1] if len(arguments) == 2 else arguments
                runtime("range", values)
            elif name == "list":
                if not arguments:
                    runtime("new", [2 if item["type"] == "i16[]" else 1])
                elif arguments[0]["kind"] in {"list", "comprehension"} or arguments[0].get("name") == "range" and arguments[0]["kind"] == "builtin":
                    expression(arguments[0])
                else:
                    runtime("copy", arguments)
            elif name == "abs":
                expression(arguments[0]); end = label()
                emit("bit 7,h", f"jp z,{end}", "ld a,l", "cpl", "ld l,a", "ld a,h", "cpl", "ld h,a", "inc hl")
                mark(end)
            elif item.get("scalar"):
                expression(arguments[0])
                for argument in arguments[1:]:
                    emit("push hl"); expression(argument); emit("ex de,hl", "pop hl", "push hl", "push de",
                        "ld a,h", "xor 128", "ld h,a", "ld a,d", "xor 128", "ld d,a", "or a", "sbc hl,de", "pop de", "pop hl")
                    keep = label()
                    emit(f"jp {'c' if name == 'min' else 'nc'},{keep}", "ex de,hl")
                    mark(keep)
            else:
                runtime(name, [*arguments, 0] if name == "sum" and len(arguments) == 1 else arguments)
        elif kind == "index":
            runtime("get", [item["base"], item["index"]])
        elif kind == "method":
            arguments = [item["base"], *item["arguments"]]
            if item["name"] == "pop" and not item["arguments"]:
                arguments.append(-1)
            runtime(item["name"], arguments)
        elif kind == "graphics":
            if item["name"] in {"pixel_on", "pixel_off", "flip_pixel"}:
                expression(item["arguments"][0])
                emit("push hl")
                expression(item["arguments"][1])
                emit("ex de,hl", "pop hl", f"call __gfx_{item['name']}")
            else:
                for argument in item["arguments"]:
                    expression(argument)
                    emit("push hl")
                emit(f"call __gfx_{item['name']}")
                emit(*(["pop de"] * len(item["arguments"])))
            pixels_used.add(item["name"])
        elif kind == "call":
            # Arguments are evaluated left-to-right and passed as word copies.
            # Nested calls preserve IX and all expression temporaries on stack.
            for argument in item["arguments"]:
                expression(argument)
                if str(argument["type"]).endswith("[]") and not argument.get("owned"):
                    emit("push hl", "call __arr_retain", "pop de")
                emit("push hl")
            emit(f"call {item['symbol']}")
            for _ in item["arguments"]:
                emit("pop de")  # Caller cleanup, preserving the result in HL.
        elif kind == "membership":
            runtime("contains", [item["left"], item["right"]])
            if item["negate"]:
                emit("ld a,l", "xor 1", "ld l,a")
        elif kind == "not":
            expression(item["value"])
            emit("ld a,l", "xor 1", "ld l,a", "ld h,0")
        elif kind == "negate":
            expression(item["value"])
            emit("ex de,hl", "ld hl,0", "or a", "sbc hl,de")
        elif kind in {"compare", "compare_chain", "and", "or"}:
            false, end = label(), label()
            branch_false(item, false)
            emit("ld hl,1", f"jp {end}")
            mark(false)
            emit("ld hl,0")
            mark(end)
        elif kind == "modulo":
            expression(item["left"])
            right = item["right"]
            divisor = right["value"] if right["kind"] == "number" else 0
            if 0 < divisor <= 256 and divisor & (divisor - 1) == 0:
                emit("ld a,l", f"and {divisor - 1}", "ld l,a", "ld h,0")
            else:
                emit("push hl")
                expression(right)
                emit("ex de,hl", "pop hl", "call __math_mod")
                modulo_used = True
        else:
            expression(item["left"])
            emit("push hl")
            expression(item["right"])
            emit("ex de,hl", "pop hl")
            if kind in {"multiply", "floor_divide"}:
                helper = "mul" if kind == "multiply" else "div"
                math_used.add(helper)
                emit(f"call __math_{helper}")
            elif kind == "add":
                emit("add hl,de")
            else:
                emit("or a", "sbc hl,de")

    def branch_false(item, false):
        if item["kind"] == "compare_chain":
            expression(item["operands"][0])
            for i, (operator, right) in enumerate(zip(item["operators"], item["operands"][1:])):
                more = i < len(item["operators"]) - 1
                fail, success = label(), label()
                emit("push hl")
                expression(right)
                emit("ex de,hl", "pop hl")
                if more: emit("push de")
                emit("or a", "sbc hl,de")
                comparison_flags(operator, fail if more else false)
                if more:
                    emit("pop hl", f"jp {success}")
                    mark(fail); emit("pop de", f"jp {false}"); mark(success)
            return
        if item["kind"] == "and":
            branch_false(item["left"], false); branch_false(item["right"], false)
            return
        if item["kind"] == "or":
            right, end = label(), label()
            branch_false(item["left"], right)
            emit(f"jp {end}"); mark(right)
            branch_false(item["right"], false); mark(end)
            return
        if item["kind"] != "compare":
            expression(item)
            emit("ld a,h", "or l", f"jp z,{false}")
            return
        op = item["operator"]
        left, right = item["left"], item["right"]
        if op in {"==", "!="} and right["kind"] == "number" and right["value"] == 0:
            if left["kind"] == "modulo" and left["right"]["kind"] == "number":
                divisor = left["right"]["value"]
                if 0 < divisor <= 256 and divisor & (divisor - 1) == 0:
                    expression(left["left"])
                    emit("ld a,l", f"and {divisor - 1}", f"jp {'nz' if op == '==' else 'z'},{false}")
                    return
            expression(left)
            emit("ld a,h", "or l", f"jp {'nz' if op == '==' else 'z'},{false}")
            return
        expression(item["left"])
        emit("push hl")
        expression(item["right"])
        emit("ex de,hl", "pop hl", "or a", "sbc hl,de")
        comparison_flags(op, false)

    def comparison_flags(op, false):
        if op in {"==", "!="}:
            emit(f"jp {'nz' if op == '==' else 'z'},{false}")
            return
        # Signed ordering: S XOR V means less-than. Z handles strict/inclusive
        # equality. JP does not change these flags between tests.
        true, overflow = label(), label()
        if op == ">":
            emit(f"jp z,{false}")
        elif op == "<=":
            emit(f"jp z,{true}")
        negative_is_true = op in {"<", "<="}
        emit(f"jp pe,{overflow}", f"jp {'m' if negative_is_true else 'p'},{true}", f"jp {false}")
        mark(overflow)
        emit(f"jp {'p' if negative_is_true else 'm'},{true}", f"jp {false}")
        mark(true)

    def statements(body):
        nonlocal modulo_used
        for statement in body:
            kind = statement["kind"]
            if statement.get("unreachable") or kind == "function":
                continue
            code.append(f"; Line {statement['line']}: {kind} {statement.get('name', '')}")
            if kind == "pass":
                continue
            if kind == "expression_statement":
                expression(statement["value"])
                if statement["value"].get("owned"):
                    emit("push hl", "call __arr_release", "pop de")
                continue
            if kind == "collect":
                emit("pop hl", "push hl", "push hl")
                expression(statement["value"])
                emit("push hl", "call __arr_append", "pop de", "pop de")
                continue
            if kind == "prepare_row_mask":
                load(statement["source"]); read_length(); store(statement["mask"]["length"])
                load(statement["source"]); emit("push hl")
                buffer_address(statement["mask"]["buffer"]); emit("push hl", f"ld hl,{int(statement['parity'])}", "push hl", "call __gfx_build_row_mask", "pop de", "pop de", "pop de")
                store(statement["mask"]["last"])
                pixels_used.add("build_row_mask")
                continue
            if kind == "pixel_row":
                end = label()
                load(statement["mask"]["length"]); emit("ld a,h", "or l", f"jp z,{end}")
                load(statement["mask"]["last"]); store(statement["target"])
                load(statement["row"])
                emit("ld a,h", "or a", f"jp nz,{end}", "ld a,l", "cp 64", f"jp nc,{end}", "add hl,hl", "add hl,hl", "push hl", "add hl,hl", "pop de", "add hl,de", "ld de,0x9340", "add hl,de", "push hl")
                buffer_address(statement["mask"]["buffer"])
                mode = {"pixel_on": "or_row", "pixel_off": "and_row", "flip_pixel": "xor_row"}[statement["mode"]]
                emit("ex de,hl", "pop hl", f"call __gfx_{mode}")
                mark(end); pixels_used.add(mode)
                continue
            if kind == "index_assign":
                target = statement["target"]
                expression(target["base"])
                emit("push hl")
                expression(target["index"])
                emit("push hl")
                if statement["operator"] != "=":
                    # Preserve the original descriptor/index, and evaluate the
                    # index exactly once even if it contains a function call.
                    emit("pop de", "pop hl", "push hl", "push de", "push hl", "push de",
                         "call __arr_get", "pop de", "pop de", "push hl")
                expression(statement["value"])
                if statement["operator"] != "=":
                    emit("ex de,hl", "pop hl")
                    operator = statement["operator"]
                    if operator in {"*=", "//=", "%="}:
                        helper = {"*=": "mul", "//=": "div", "%=": "mod"}[operator]
                        if helper == "mod":
                            modulo_used = True
                        else:
                            math_used.add(helper)
                        emit(f"call __math_{helper}")
                    else:
                        emit(*(["add hl,de"] if operator == "+=" else ["or a", "sbc hl,de"]))
                emit("push hl", "call __arr_set", "pop de", "pop de", "pop de")
                if target["base"].get("owned"):
                    emit("push de", "call __arr_release", "pop de")
                continue
            if kind == "return":
                if statement["value"] is not None:
                    expression(statement["value"])
                    if statement["value"]["type"].endswith("[]") and not statement["value"].get("owned"):
                        emit("push hl", "call __arr_retain", "pop de")
                emit(f"jp {return_label}")
                continue
            if kind == "while":
                start, end = label(), label()
                mark(start)
                branch_false(statement["condition"], end)
                loops.append((start, end))
                statements(statement["body"])
                loops.pop()
                emit(f"jp {start}")
                mark(end)
                continue
            if kind == "for":
                if "fast_range" in statement:
                    info, current = statement["fast_range"], statement["range_current"]
                    start, advance, end = label(), label(), label()
                    emit(f"ld hl,{info['start'] & 65535}"); store(current)
                    mark(start)
                    load(current); store(statement["target"])
                    loops.append((advance, end)); statements(statement["body"]); loops.pop()
                    mark(advance); load(current)
                    if info["byte_compare"]:
                        emit("ld a,l", f"cp {info['last']}", f"jp z,{end}")
                    else:
                        emit("push hl", f"ld de,{info['last'] & 65535}", "or a", "sbc hl,de", "pop hl", f"jp z,{end}")
                    step = info["step"]
                    if abs(step) <= 3: emit(*(["inc hl" if step > 0 else "dec hl"] * abs(step)))
                    else: emit(f"ld de,{step & 65535}", "add hl,de")
                    store(current); emit(f"jp {start}"); mark(end)
                    continue
                if statement["iteration_kind"] == "range":
                    current, stop_slot, step = [statement[field] for field in ("range_current", "range_stop", "range_step")]
                    arguments = statement["iterable"]["arguments"]
                    arguments = [0, arguments[0], 1] if len(arguments) == 1 else [*arguments, 1] if len(arguments) == 2 else arguments
                    for argument, slot in zip(arguments, [current, stop_slot, step]):
                        if isinstance(argument, int): emit(f"ld hl,{argument}")
                        else: expression(argument)
                        store(slot)
                    start, negative, body, advance, negative_advance, update, end = [label() for _ in range(7)]
                    load(step); emit("ld a,h", "or l", f"jp nz,{start}", "ld hl,7", "jp __arr_fail")
                    mark(start)
                    load(step); emit("bit 7,h", f"jp nz,{negative}")
                    def range_condition(operator):
                        branch_false({"kind": "compare", "operator": operator,
                                      "left": {**current, "kind": "name"}, "right": {**stop_slot, "kind": "name"}}, end)
                    range_condition("<"); emit(f"jp {body}")
                    mark(negative); range_condition(">")
                    mark(body)
                    load(current); store(statement["target"])
                    loops.append((advance, end)); statements(statement["body"]); loops.pop()
                    mark(advance)
                    load(step); emit("bit 7,h", f"jp nz,{negative_advance}", "push hl")
                    load(stop_slot); emit("push hl"); load(current)
                    emit("ex de,hl", "pop hl", "or a", "sbc hl,de", "pop de", "or a", "sbc hl,de", f"jp c,{end}", f"jp z,{end}", f"jp {update}")
                    mark(negative_advance)
                    load(step); emit("ld a,l", "cpl", "ld l,a", "ld a,h", "cpl", "ld h,a", "inc hl", "push hl")
                    load(current); emit("push hl"); load(stop_slot)
                    emit("ex de,hl", "pop hl", "or a", "sbc hl,de", "pop de", "or a", "sbc hl,de", f"jp c,{end}", f"jp z,{end}")
                    mark(update)
                    load(current); emit("push hl"); load(step); emit("ex de,hl", "pop hl", "add hl,de"); store(current)
                    emit(f"jp {start}"); mark(end)
                    continue
                iterators = statement["iterators"]
                index = statement["iteration_index"]
                start, advance, end = label(), label(), label()
                for source, iterator in zip(statement["sources"], iterators):
                    expression(source)
                    if not source.get("owned"):
                        emit("push hl", "call __arr_retain", "pop de")
                    emit("push hl")
                    load(iterator)
                    emit("push hl", "call __arr_release", "pop de", "pop hl")
                    store(iterator)
                if statement["iteration_kind"] == "enumerate":
                    expression(statement["enumeration_start"])
                    store(statement["enumeration"])
                emit("ld hl,0")
                store(index)
                mark(start)
                for iterator in iterators:
                    load(iterator)
                    emit("inc hl", "inc hl", "ld e,(hl)", "inc hl", "ld d,(hl)")
                    load(index)
                    emit("or a", "sbc hl,de", f"jp nc,{end}")
                # The loop just checked index < current length. No user code
                # runs between that check and this read, so normalization and
                # a second bounds check inside __arr_get would be redundant.
                if statement["iteration_kind"] == "enumerate":
                    load(statement["enumeration"])
                    store(statement["targets"][0])
                for iterator, target in zip(iterators, statement["targets"][-len(iterators):]):
                    load(index)
                    if iterator["type"] == "i16[]":
                        emit("add hl,hl")
                    emit("push hl")
                    load(iterator)
                    emit("ld e,(hl)", "inc hl", "ld d,(hl)", "ex de,hl", "pop de", "add hl,de")
                    if iterator["type"] == "i16[]":
                        emit("ld e,(hl)", "inc hl", "ld d,(hl)", "ex de,hl")
                    else:
                        emit("ld l,(hl)", "ld h,0")
                    store(target)
                loops.append((advance, end))
                statements(statement["body"])
                loops.pop()
                mark(advance)
                load(index)
                emit("inc hl")
                store(index)
                if statement["iteration_kind"] == "enumerate":
                    load(statement["enumeration"]); emit("inc hl"); store(statement["enumeration"])
                emit(f"jp {start}")
                mark(end)
                for iterator in iterators:
                    load(iterator)
                    emit("push hl", "call __arr_release", "pop de", "ld hl,0")
                    store(iterator)
                continue
            if kind in {"break", "continue"}:
                start, end = loops[-1]
                emit(f"jp {end if kind == 'break' else start}")
                continue
            if kind == "if":
                false, end = label(), label()
                branch_false(statement["condition"], false)
                statements(statement["body"])
                emit(f"jp {end}")
                mark(false)
                statements(statement["alternative"])
                mark(end)
                continue
            expression(statement["value"])
            if statement["type"].endswith("[]"):
                if not statement["value"].get("owned"):
                    emit("push hl", "call __arr_retain", "pop de")
                emit("push hl")
                load(statement)
                emit("push hl", "call __arr_release", "pop de", "pop hl")
            store(statement)

    if errors_used:
        emit("ld (__list_main_sp),sp", "ld (__list_main_ix),ix")
    if lists_used:
        emit("call __arr_init")
    if native_used & {"random.seed", "random.randint"}:
        emit("ld a,r", "ld l,a", "ld h,173", "ld (__native_rng_state),hl")
    statements(tree["body"])
    # Keep the CPU from executing the variable slots as instructions.
    emit("ret")
    for function in tree["body"]:
        if function["kind"] != "function":
            continue
        code.extend(["", f"; Function {function['name']}: per-call IX stack frame"])
        mark(function["label"])
        emit("push ix", "ld ix,0", "add ix,sp")
        if function["frame_size"]:
            emit(f"ld hl,{(-function['frame_size']) & 0xFFFF}", "add hl,sp", "ld sp,hl")
        return_label = label()
        array_locals = [value for value in function["locals"].values() if value["type"].endswith("[]")]
        if array_locals:
            emit("ld hl,0")
            for value in array_locals:
                if value["offset"] < 0:
                    store({**value, "symbol": value["label"]})
        statements(function["body"])
        if function["return_type"] == "void":
            emit("ld hl,0")
        mark(return_label)
        if array_locals:
            emit("push hl")
            for value in array_locals:
                load({**value, "symbol": value["label"]})
                emit("push hl", "call __arr_release", "pop de")
            emit("pop hl")
        emit("ld sp,ix", "pop ix", "ret")
    if native_used:
        from .native_runtime import assembly as native_assembly
        code.append(native_assembly(native_used))
    if modulo_used:
        from .math_runtime import MODULO
        code.append(MODULO)
    if math_used:
        from .math_runtime import MULTIPLY, FLOOR_DIVIDE
        code.extend({"mul": MULTIPLY, "div": FLOOR_DIVIDE}[name] for name in sorted(math_used))
    required = set(RUNTIME_TARGET.findall("\n".join(code)))
    if required:
        code.extend(["", "; Used array runtime routines and their dependencies", runtime_assembly(required)])
    if pixels_used:
        from .graphics_runtime import graphics_assembly
        code.append(graphics_assembly(pixels_used))
    for values, label_name in constant_data.items():
        code.append(label_name + ":")
        for start in range(0, len(values), 24):
            code.append("        db " + ",".join(str(value) for value in values[start:start + 24]))
    code.extend(["", "; Variable storage"])
    for name, symbol in symbols.items():
        directive = "db" if symbol["size"] == 1 else "dw"
        code.append(f"{symbol['label']}: {directive} 0 ; {name}: {symbol['type']}")
    for symbol in tree.get("temporaries", {}).values():
        code.append(f"{symbol['label']}: dw 0")
    for symbol in tree.get("drawing_buffers", []):
        code.append(f"{symbol['label']}: defs {symbol['size']},0")
    if errors_used:
        code.extend(["__list_error: dw 0", "__list_main_sp: dw 0", "__list_main_ix: dw 0"])
    if lists_used:
        code.extend(["__heap_start:", f"        defs {HEAP_BYTES},0", "__heap_end:"])
    return optimize("\n".join(code) + "\n")
