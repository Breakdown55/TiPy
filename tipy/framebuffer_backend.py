"""Cost-based lowering of symbolic static frames to compact Z80 byte operations."""

from collections import Counter


def period(data):
    prefix = [0] * len(data)
    for i in range(1, len(data)):
        j = prefix[i - 1]
        while j and data[i] != data[j]: j = prefix[j - 1]
        if data[i] == data[j]: j += 1
        prefix[i] = j
    return len(data) - prefix[-1] if data else 0


def runs(data):
    output = []
    index = 0
    while index < len(data):
        end = index + 1
        while end < len(data) and data[end] == data[index] and end - index < 255: end += 1
        output.extend([end - index, data[index]])
        index = end
    return output + [0]


def patch_code(previous, frame):
    old_keep, old_bits = previous
    keep, bits = frame
    code, size, last = [], 0, None
    for index in range(768):
        if old_keep[index] == keep[index] and old_bits[index] == bits[index]: continue
        address = 0x9340 + index
        if last is not None and address == last + 1:
            code.append("inc hl"); size += 1
        else:
            code.append(f"ld hl,{address}"); size += 3
        mask = keep[index]
        value = ((old_bits[index] ^ bits[index]) & mask) | (bits[index] & (255 ^ mask))
        if mask == 0:
            code.append(f"ld (hl),{value}"); size += 2
        elif mask == (255 ^ value) and value and value & (value - 1) == 0:
            code.append(f"set {value.bit_length() - 1},(hl)"); size += 2
        elif value == 0 and mask != 255 and (255 ^ mask) & ((255 ^ mask) - 1) == 0:
            code.append(f"res {(255 ^ mask).bit_length() - 1},(hl)"); size += 2
        else:
            code.append("ld a,(hl)"); size += 1
            if mask == (255 ^ value):
                code.append(f"or {value}"); size += 2
            else:
                if mask != 255: code.append(f"and {mask}"); size += 2
                if value: code.append(f"xor {value}"); size += 2
            code.append("ld (hl),a"); size += 1
        last = address
    return code, size


def lower_frames(frames):
    previous = (bytes([255]) * 768, bytes(768))
    output = []
    for keep, bits in frames:
        patches, patch_size = patch_code(previous, (keep, bits))
        choices = [(patch_size, {"encoding": "patches", "instructions": patches})]
        if not any(keep):
            background = Counter(bits).most_common(1)[0][0]
            sparse, sparse_size = patch_code((bytes(768), bytes([background]) * 768), (keep, bits))
            if sparse:
                choices.append((13 + sparse_size, {"encoding": "fill_patches", "value": background, "instructions": sparse}))
            p = period(bits)
            if p == 1:
                choices.append((13, {"encoding": "fill", "value": bits[0]}))
            else:
                choices.append(((22 if p < 768 else 11) + p, {"encoding": "pattern", "data": list(bits[:p])}))
            encoded = runs(bits)
            # Charge the decoder on every frame: conservative for shared code.
            choices.append((len(encoded) + 34, {"encoding": "rle", "data": encoded}))
        output.append(min(choices, key=lambda choice: choice[0])[1])
        previous = keep, bits
    return output


def generate_frames(frames):
    code = ["; Generated by TiPy", "; Aggressive: compile-time evaluation + observable-effect elimination", "        org 0x9D95"]
    data, cache, decoder = [], {}, False
    def emit(*items): code.extend("        " + item for item in items)
    def blob(values):
        key = tuple(values)
        if key not in cache:
            label = f"__frame_data_{len(cache)}"
            cache[key] = label
            data.append(label + ":")
            for start in range(0, len(values), 24):
                data.append("        db " + ",".join(str(v) for v in values[start:start + 24]))
        return cache[key]
    for index, frame in enumerate(frames):
        code.append(f"; Observable render {index + 1}: {frame['encoding']}")
        encoding = frame["encoding"]
        if encoding == "patches": emit(*frame["instructions"])
        elif encoding in {"fill", "fill_patches"}:
            emit("ld hl,0x9340", f"ld (hl),{frame['value']}", "ld de,0x9341", "ld bc,767", "ldir")
            if encoding == "fill_patches": emit(*frame["instructions"])
        elif encoding == "pattern":
            values = frame["data"]
            emit(f"ld hl,{blob(values)}", "ld de,0x9340", f"ld bc,{len(values)}", "ldir")
            if len(values) < 768:
                emit("ld hl,0x9340", f"ld de,{0x9340 + len(values)}", f"ld bc,{768 - len(values)}", "ldir")
        elif encoding == "rle":
            emit(f"ld hl,{blob(frame['data'])}", "ld de,0x9340", "call __frame_rle")
            decoder = True
        emit("push ix", "push iy", "rst 0x28", "dw 0x486a", "pop iy", "pop ix")
    emit("ret")
    if decoder:
        code.extend(["__frame_rle:", "        ld b,(hl)", "        inc hl", "        ld a,b", "        or a", "        ret z",
                     "        ld a,(hl)", "        inc hl", "__frame_rle_run:", "        ld (de),a", "        inc de",
                     "        djnz __frame_rle_run", "        jr __frame_rle"])
    code.extend(data)
    return "\n".join(code) + "\n"
